// Langue de la page d'après celle du téléphone ; français par défaut.
export function langueDe(langue) {
  const l = String(langue || '').toLowerCase();
  if (l.startsWith('de')) return 'de';
  if (l.startsWith('en')) return 'en';
  return 'fr';
}
